// Regenerates supabase/functions/_shared/yatzy/optimal-table-data.ts (run: bun scripts/build-yatzy-optimal.ts)
import { buildTable, encodeTable } from '../supabase/functions/_shared/yatzy/optimal';
import { writeFileSync } from 'node:fs';
const t0 = Date.now();
const T = buildTable(m => process.stdout.write(`\r${m}   `));
console.log(`\nE(start)=${T[0].toFixed(3)} in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
const b64 = Buffer.from(encodeTable(T)).toString('base64');
writeFileSync('supabase/functions/_shared/yatzy/optimal-table-data.ts',
  `// GENERATED by scripts/build-yatzy-optimal.ts — do not edit.\nexport const OPTIMAL_TABLE_B64 =\n  '${b64}';\n`);
console.log(`wrote ${(b64.length / 1e6).toFixed(2)} MB`);
